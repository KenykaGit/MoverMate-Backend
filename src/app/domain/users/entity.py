from dataclasses import dataclass
from typing import Self

from app.domain.common.entity import Entity
from app.domain.common.ids import UserId, new_id
from app.domain.users.value_objects import Email, PasswordHash, Username


@dataclass(eq=False, kw_only=True, slots=True)
class User(Entity[UserId]):
    email: Email
    username: Username
    password_hash: PasswordHash
    is_active: bool
    """Soft-delete flag: False means the user is deleted but the data is kept."""

    @classmethod
    def register(cls, *, email: Email, username: Username, password_hash: PasswordHash) -> Self:
        """A new active user. The identity is generated by the domain."""
        return cls(
            id=UserId(new_id()),
            email=email,
            username=username,
            password_hash=password_hash,
            is_active=True,
        )

    def soft_delete(self) -> None:
        """Idempotent. Frees the email and username for other users."""
        self.is_active = False

    def restore(self) -> None:
        """Idempotent. Undoes a soft delete."""
        self.is_active = True

    def change_email(self, email: Email) -> None:
        self.email = email

    def change_username(self, username: Username) -> None:
        self.username = username

    def change_password(self, password_hash: PasswordHash) -> None:
        self.password_hash = password_hash
